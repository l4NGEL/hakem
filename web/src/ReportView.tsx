import type { Comment, Issue, Job, Severity } from "./api";

const SEVERITY_ORDER: Severity[] = ["high", "medium", "low"];
const SEVERITY_LABEL: Record<Severity, string> = { high: "High", medium: "Medium", low: "Low" };
const SCORE_LABEL: Record<string, string> = {
  clarity: "Clarity",
  methodology: "Methodology",
  evidence: "Evidence",
  contribution_stated: "Contribution stated",
  writing: "Writing",
};

function IssueList({ issues }: { issues: Issue[] }) {
  if (issues.length === 0) {
    return <p className="muted">No structural problems found.</p>;
  }
  return (
    <>
      {SEVERITY_ORDER.map((sev) => {
        const group = issues.filter((i) => i.severity === sev);
        if (group.length === 0) return null;
        return (
          <div key={sev} className="sev-group">
            <h4>
              <span className={`badge ${sev}`}>{SEVERITY_LABEL[sev]}</span> {group.length}
            </h4>
            <ul>
              {group.map((i, n) => (
                <li key={n}>
                  {i.message}
                  {i.line != null && <span className="muted"> · line {i.line}</span>}
                </li>
              ))}
            </ul>
          </div>
        );
      })}
    </>
  );
}

function Comments({ title, items }: { title: string; items: Comment[] }) {
  if (items.length === 0) return null;
  return (
    <>
      <h4>{title}</h4>
      <ol className="comments">
        {items.map((c, n) => (
          <li key={n}>
            <strong>{c.section}:</strong> {c.issue}
            <div className="suggestion">{c.suggestion}</div>
          </li>
        ))}
      </ol>
    </>
  );
}

export function ReportView({ job }: { job: Job }) {
  if (job.status === "FAILED") {
    return <div className="card error" role="alert">Analysis failed: {job.error ?? "unknown error"}</div>;
  }
  if (job.status !== "DONE" || !job.report) {
    return (
      <div className="card" aria-live="polite">
        <span className="spinner" /> {job.status === "QUEUED" ? "Waiting in queue…" : "Analysing…"}
      </div>
    );
  }
  const { checks, review, review_error } = job.report;
  const stats = checks.stats;

  return (
    <div className="report">
      <section className="card">
        <h3>Automated checks</h3>
        <p className="muted">
          {stats.words} words · abstract {stats.abstract_words ?? "—"} words · {stats.reference_entries} references ·{" "}
          {checks.sections.filter((s) => s.key).length} recognised sections
        </p>
        <IssueList issues={checks.issues} />
      </section>

      <section className="card">
        <h3>Reviewer feedback</h3>
        {review ? (
          <>
            {review.injection_attempt_detected && (
              <p className="warn" role="alert">
                The manuscript contains text addressed to the reviewer (for example, a request for a high score). It
                was treated as part of the manuscript and ignored.
              </p>
            )}
            <p>{review.summary}</p>
            <dl className="scores">
              {Object.entries(review.scores).map(([k, v]) => (
                <div key={k}>
                  <dt>{SCORE_LABEL[k] ?? k}</dt>
                  <dd>
                    <meter min={1} max={5} value={v} aria-label={`${SCORE_LABEL[k] ?? k} ${v} of 5`} /> {v}/5
                  </dd>
                </div>
              ))}
            </dl>
            {review.strengths.length > 0 && (
              <>
                <h4>Strengths</h4>
                <ul>{review.strengths.map((s, n) => <li key={n}>{s}</li>)}</ul>
              </>
            )}
            <Comments title="Major issues" items={review.major_issues} />
            <Comments title="Minor issues" items={review.minor_issues} />
            <p className="muted small">Generated by {review.model}. Treat as a second opinion, not a verdict.</p>
          </>
        ) : (
          <p className="muted">
            {review_error ?? "LLM review is not enabled on this server; only the automated checks were run."}
          </p>
        )}
      </section>
    </div>
  );
}
